"""
MediGuide AI - Report Analyzer Service
-----------------------------------------
Uses Google Gemini AI to analyze medical reports (text or extracted PDF text).
Returns a structured JSON-compatible dict with:
  - summary
  - key_findings  (list)
  - risk_flags    (list)
  - recommendations (list)
  - disclaimer
"""

import os
import io
import json
import re
import google.generativeai as genai
from dotenv import load_dotenv

load_dotenv()
genai.configure(api_key=os.getenv("GEMINI_API_KEY"))

MODEL_NAME = "models/gemini-3.6-flash"

# Matches values such as "Hemoglobin: 11.2 g/dL" and "WBC: 11,500/uL".
_METRIC_RE = re.compile(
    r'([A-Za-z][A-Za-z0-9 /()\-]+?)'
    r'\s*[:=–—]\s*'
    r'([\d,]+\.?\d*)'
    r'\s*'
    r'([a-zA-Z/%µμ][a-zA-Z/%µμ·\d]*(?:/[a-zA-Z/%µμ·\d]+)?)?'
)


# ── Helpers ──────────────────────────────────────────────────────────────────

def extract_health_metrics(analysis: dict) -> list[dict]:
    """Extract numeric health metrics from the model's findings and risk flags."""
    if not analysis:
        return []

    metrics = []
    seen = set()
    risk_texts = set(analysis.get("risk_flags", []))

    for finding_text in list(analysis.get("key_findings", [])) + list(analysis.get("risk_flags", [])):
        for match in _METRIC_RE.finditer(str(finding_text)):
            name = match.group(1).strip().rstrip(':=–— ')
            if name.lower() in {"normal", "range", "age", "date", "patient", "report"}:
                continue

            try:
                value = float(match.group(2).replace(",", ""))
            except ValueError:
                continue

            key = name.lower()
            if key in seen:
                continue
            seen.add(key)
            metrics.append({
                "name": name,
                "value": value,
                "unit": (match.group(3) or "").strip(),
                "flagged": finding_text in risk_texts,
            })

    return metrics


def _extract_text_from_pdf(file_bytes: bytes) -> str:
    """
    Extract plain text from a PDF byte stream using PyPDF2 if available,
    falling back to a raw byte decode attempt.
    """
    try:
        import PyPDF2
        reader = PyPDF2.PdfReader(io.BytesIO(file_bytes))
        pages  = [page.extract_text() or "" for page in reader.pages]
        return "\n".join(pages).strip()
    except Exception:
        # Last-resort: decode bytes as latin-1 (won't be perfect but better than crash)
        return file_bytes.decode("latin-1", errors="ignore")


def _clean_json_block(raw: str) -> str:
    """Strip markdown fences like ```json … ``` from a Gemini response."""
    raw = raw.strip()
    raw = re.sub(r"^```(?:json)?\s*", "", raw)
    raw = re.sub(r"\s*```$", "", raw)
    return raw.strip()


# ── Main Entry Point ─────────────────────────────────────────────────────────

def analyze_report(report_text: str) -> dict:
    """
    Send `report_text` to Gemini and return a structured analysis dict.

    Returns dict with keys:
        summary         : str
        key_findings    : list[str]
        risk_flags      : list[str]    (empty list if none)
        recommendations : list[str]
        disclaimer      : str

    On error, returns a dict with an 'error' key.
    """

    if not report_text or len(report_text.strip()) < 20:
        return {"error": "The provided report text is too short to analyze. Please paste more content or upload a valid file."}

    prompt = f"""
You are MediGuide AI, a medical report analysis assistant.

Analyze the following medical report text and respond ONLY with a valid JSON object (no markdown, no code fences).

Required JSON structure:
{{
  "summary": "<2-3 sentence plain-language summary of what this report is about>",
  "key_findings": [
    "<finding 1>",
    "<finding 2>",
    "..."
  ],
  "risk_flags": [
    "<any abnormal or concerning value — include the metric name and value>",
    "..."
  ],
  "recommendations": [
    "<actionable recommendation 1>",
    "<actionable recommendation 2>",
    "..."
  ],
  "disclaimer": "This analysis is generated by AI for informational purposes only and is not a substitute for professional medical advice. Consult a qualified healthcare provider for diagnosis and treatment."
}}

Rules:
- key_findings: list 3-7 most important observations from the report.
- risk_flags: list values that are outside normal ranges or require attention. If everything is normal, return an empty list [].
- recommendations: list 3-5 specific, actionable steps the patient should consider.
- Keep all text simple and patient-friendly (avoid heavy jargon).
- DO NOT prescribe specific medications or dosages.
- Return ONLY the raw JSON object, nothing else.

Medical Report Text:
\"\"\"
{report_text[:4000]}
\"\"\"
"""

    try:
        model    = genai.GenerativeModel(MODEL_NAME)
        response = model.generate_content(prompt)
        raw      = _clean_json_block(response.text)
        result   = json.loads(raw)

        # Ensure all expected keys are present with sane defaults
        result.setdefault("summary", "No summary available.")
        result.setdefault("key_findings", [])
        result.setdefault("risk_flags", [])
        result.setdefault("recommendations", [])
        result.setdefault(
            "disclaimer",
            "This analysis is for informational purposes only. Consult a doctor."
        )
        result["health_metrics"] = extract_health_metrics(result)
        return result

    except json.JSONDecodeError:
        # Gemini returned non-JSON — surface a graceful error with raw text
        return {
            "error": "AI response could not be parsed. Please try again.",
            "raw_response": response.text if 'response' in locals() else ""
        }
    except Exception as e:
        return {"error": f"Analysis failed: {str(e)}"}
